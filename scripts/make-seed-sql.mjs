// Writes supabase/02-history.sql: the imported master sheet as SQL inserts.
// Usage: node scripts/make-seed-sql.mjs
import { writeFileSync } from 'node:fs';
import { PLAYERS, GUESTS, HIST, BASE_SEASONS } from '../src/data/seed.js';

const q = v => v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const look = p => q(JSON.stringify({ skin: p.skin, hair: p.hair, style: p.style, ...(p.band ? { band: true } : {}) }));
const out = ['-- The master sheet, W24 to S26 (generated by scripts/make-seed-sql.mjs). Run after 01-schema.sql.', 'begin;'];

const seasons = BASE_SEASONS.slice().reverse();
out.push('insert into public.seasons (code, sort, is_current) values');
out.push(seasons.map((c, i) => `  (${q(c)}, ${i + 1}, ${c === 'S26'})`).join(',\n') + ';');

out.push('insert into public.players (id, name, num, role, look) values');
out.push([...PLAYERS.map(p => [p, 'starter']), ...GUESTS.map(p => [p, 'sub'])]
  .map(([p, role]) => `  (${q(p.id)}, ${q(p.name)}, ${q(String(p.num))}, ${q(role)}, ${look(p)})`).join(',\n') + ';');

const opps = {};
HIST.forEach(([s, , , o]) => { const l = opps[s] ||= []; if (!l.includes(o)) l.push(o); });
out.push('insert into public.season_opponents (season, name, pos) values');
out.push(Object.entries(opps).flatMap(([s, l]) => l.map((o, i) => `  (${q(s)}, ${q(o)}, ${i + 1})`)).join(',\n') + ';');

out.push('insert into public.games (id, season, no, date, opp) values');
out.push(HIST.map(([s, n, d, o]) => `  (${q(`${s}-${n}`)}, ${q(s)}, ${n}, ${q(d)}, ${q(o)})`).join(',\n') + ';');

out.push('insert into public.lines (game_id, player_id, pos, m2, a2, m3, a3, ftm, fta, reb, ast, stl, blk, "to") values');
out.push(HIST.flatMap(([s, n, , , rows]) => Object.entries(rows).map(([id, v], i) => `  (${q(`${s}-${n}`)}, ${q(id)}, ${i + 1}, ${v.join(', ')})`)).join(',\n') + ';');
out.push('commit;', '');

writeFileSync(new URL('../supabase/02-history.sql', import.meta.url), out.join('\n'));
console.log(`Wrote ${HIST.length} games.`);
